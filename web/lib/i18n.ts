export const dictionaries: Record<Lang, Dict> = { uz, ru, en };

export function translate(lang: Lang, key: Key): string {
  return dictionaries[lang][key] ?? dictionaries.uz[key];
}

export function errorText(lang: Lang, code: string): string {
  const key = `err.${code}` as Key;
  return key in dictionaries.uz ? translate(lang, key) : translate(lang, 'err.UNKNOWN');
}
